import pandas as pd
import numpy as np
from datetime import datetime, timedelta

# Фиксируем случайность, чтобы результаты можно было повторить
rng = np.random.default_rng(42)

# Количество пользователей
n_users = 3000

# Генерируем уникальные ID
user_ids = np.arange(1, n_users + 1)

# Операционная система
devices = rng.choice(
    ["iOS", "Android"],
    size=n_users,
    p=[0.6, 0.4]
)

# Источник привлечения
sources = rng.choice(
    ["organic", "paid_ads", "referral", "social", "direct"],
    size=n_users,
    p=[0.35, 0.25, 0.15, 0.15, 0.10]
)

# Случайная дата регистрации в течение 6 месяцев
start_date = datetime(2026, 1, 1)

registration_dates = [
    start_date + timedelta(days=int(x))
    for x in rng.integers(0, 181, size=n_users)
]

# Собираем таблицу
users = pd.DataFrame({
    "user_id": user_ids,
    "device": devices,
    "acquisition_source": sources,
    "registration_date": registration_dates
})

# Посмотрим первые 10 пользователей
users.head(10)

print("Количество пользователей:", len(users))

print("\nРаспределение по устройствам:")
print(users["device"].value_counts())

print("\nРаспределение по источникам:")
print(users["acquisition_source"].value_counts())

# Период наблюдения
end_date = datetime(2026, 7, 1)

# Тип активности каждого пользователя
activity_types = rng.choice(
    ["low", "medium", "high"],
    size=n_users,
    p=[0.55, 0.35, 0.10]
)

sessions_data = []
session_id = 1

for i, user in users.iterrows():

    user_id = int(user["user_id"])
    registration_date = user["registration_date"]
    activity_type = activity_types[i]

    # Определяем количество сессий
    if activity_type == "low":
        n_sessions = rng.integers(1, 4)

    elif activity_type == "medium":
        n_sessions = rng.integers(4, 13)

    else:
        n_sessions = rng.integers(13, 31)

    # Сколько времени пользователь находится
    # в нашем периоде наблюдения
    available_seconds = int(
        (end_date - registration_date).total_seconds()
    )

    # Генерируем моменты открытия приложения
    offsets = np.sort(
        rng.integers(
            0,
            available_seconds,
            size=n_sessions
        )
    )

    for offset in offsets:

        session_start = (
            registration_date
            + timedelta(seconds=int(offset))
        )

        sessions_data.append({
            "session_id": session_id,
            "user_id": user_id,
            "session_start": session_start
        })

        session_id += 1

# Создаем таблицу сессий
sessions = pd.DataFrame(sessions_data)

sessions.head(10)

session_counts = (
    sessions.groupby("user_id")
    .size()
    .reset_index(name="session_count")
)

session_counts["session_count"].describe()

import sqlite3

# Создаем базу данных SQLite
conn = sqlite3.connect("dental_app.db")

# Переносим таблицы в базу
users.to_sql("users", conn, if_exists="replace", index=False)
sessions.to_sql("sessions", conn, if_exists="replace", index=False)

# Проверяем, что данные записались
pd.read_sql_query("""
    SELECT
        COUNT(*) AS total_sessions,
        COUNT(DISTINCT user_id) AS unique_users
    FROM sessions
""", conn)

# Генерируем события внутри каждой сессии

events_data = []
event_id = 1

for _, session in sessions.iterrows():

    user_id = int(session["user_id"])
    session_id = int(session["session_id"])
    session_start = session["session_start"]

    current_time = session_start

    # Функция добавления события
    def add_event(event_name):
        global event_id, current_time

        events_data.append({
            "event_id": event_id,
            "user_id": user_id,
            "session_id": session_id,
            "event_name": event_name,
            "event_time": current_time
        })

        event_id += 1

        # Между действиями проходит от 10 до 120 секунд
        current_time += timedelta(
            seconds=int(rng.integers(10, 121))
        )

    # Каждый пользователь открывает приложение
    add_event("app_open")

    # 70% смотрят услуги
    if rng.random() < 0.70:

        add_event("view_services")

        # 60% открывают конкретную услугу
        if rng.random() < 0.60:

            add_event("view_service_details")

            # 50% смотрят врача
            if rng.random() < 0.50:

                add_event("view_doctor")

                # 40% выбирают время
                if rng.random() < 0.40:

                    add_event("select_time")

                    # 65% завершают бронирование
                    if rng.random() < 0.65:

                        add_event("book_appointment")

# Создаем DataFrame
events = pd.DataFrame(events_data)

# Смотрим первые строки
events.head(15)

print("Всего событий:", len(events))
print("Уникальных пользователей:", events["user_id"].nunique())
print("Уникальных сессий:", events["session_id"].nunique())

print("\nКоличество событий каждого типа:")
print(events["event_name"].value_counts())

funnel = (
    events.groupby("event_name")["user_id"]
    .nunique()
    .reindex([
        "app_open",
        "view_services",
        "view_service_details",
        "view_doctor",
        "select_time",
        "book_appointment"
    ])
    .reset_index(name="users")
)

funnel["conversion_from_open"] = (
    funnel["users"] / funnel["users"].iloc[0] * 100
).round(2)

